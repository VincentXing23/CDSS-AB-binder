"""Verify the bundled synthetic example across platforms against a reviewed reference.

The committed reference is read only. No reference is generated by this command.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import platform
import shutil
import sqlite3
import subprocess
import sys
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
FIXTURE = ROOT / "cdss-ab/examples/reproducibility"
SCRIPTS = ROOT / "cdss-ab/scripts"
PLATFORM_FILES = {"analysis.sqlite", "manifest.json"}
EXPECTED_COUNTS = {"studies": 1, "doctors": 3, "questions": 4, "answer_keys": 4,
                   "assignments": 12, "cdss_advice": 8, "responses": 12,
                   "response_changes": 3}
EXPECTED_CONDITIONS = [["T0", 4, 2], ["T1", 4, 4], ["T2", 4, 2]]


def require(condition, message):
    if not condition:
        raise ValueError(message)


def sha256(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def hashes(directory):
    files = sorted(directory.rglob("*"))
    require(not any(p.is_symlink() for p in files), "Symbolic links are not valid analysis outputs")
    return {p.relative_to(directory).as_posix(): sha256(p) for p in files if p.is_file()}


def quoted_identifier(name):
    return '"' + name.replace('"', '""') + '"'


def typed_cell(value):
    # Preserve SQLite storage types, including INTEGER versus REAL and NULL.
    if value is None:
        return ["null", None]
    if isinstance(value, bytes):
        return ["blob", value.hex()]
    if isinstance(value, int):
        return ["integer", value]
    if isinstance(value, float):
        return ["real", value]
    return ["text", value]


def database_content(path):
    """Return every schema object and every table/view value, without page layout."""
    with sqlite3.connect(f"{path.resolve().as_uri()}?mode=ro", uri=True) as conn:
        require(conn.execute("PRAGMA integrity_check").fetchall() == [("ok",)],
                "SQLite integrity check failed")
        require(conn.execute("PRAGMA foreign_key_check").fetchall() == [],
                "SQLite foreign key check failed")
        schema = [list(row) for row in conn.execute(
            "SELECT type, name, tbl_name, sql FROM sqlite_master ORDER BY type, name")]
        relations = {}
        for kind, name, _, _ in schema:
            if kind not in {"table", "view"}:
                continue
            cursor = conn.execute(f"SELECT * FROM {quoted_identifier(name)}")
            rows = [[typed_cell(cell) for cell in row] for row in cursor.fetchall()]
            rows.sort(key=lambda row: json.dumps(row, ensure_ascii=False, separators=(",", ":")))
            relations[name] = {"columns": [column[0] for column in cursor.description], "rows": rows}
        metadata = {name: conn.execute(f"PRAGMA {name}").fetchone()[0]
                    for name in ("encoding", "user_version", "application_id")}
    return {"schema": schema, "relations": relations, "metadata": metadata}


def load_reference():
    reference = json.loads((FIXTURE / "portable-reference.json").read_text(encoding="utf-8"))
    strict_path = FIXTURE / "reference-sha256.json"
    require(reference["format_version"] == 1, "Unsupported portable reference format")
    require(sha256(strict_path) == reference["strict_reference_sha256"],
            "Committed strict reference has changed")
    strict = json.loads(strict_path.read_text(encoding="utf-8"))
    require(len(strict) == 22 and PLATFORM_FILES <= strict.keys(), "Expected the reviewed 22-file reference")
    for name, expected in reference["source_script_sha256"].items():
        require(sha256(SCRIPTS / name) == expected, f"Analysis source changed: {name}")
    return reference, strict


def verify_manifest(run, reference, actual):
    manifest = json.loads((run / "manifest.json").read_text(encoding="utf-8"))
    metadata = {key: value for key, value in manifest.items() if key != "files"}
    require(metadata == reference["manifest_metadata"], "Manifest metadata differs from reviewed reference")
    expected_entries = {name: {"sha256": digest, "bytes": (run / name).stat().st_size}
                        for name, digest in actual.items() if name != "manifest.json"}
    require(manifest.get("files") == expected_entries,
            "Manifest file set, hashes, sizes, or entry fields are incorrect")
    require(manifest["analysis_script_sha256"] == sha256(SCRIPTS / "analyze_real_doctor_collection.py"),
            "Manifest analysis-script hash does not match source")


def verify_known_results(run):
    summary = json.loads((run / "summary.json").read_text(encoding="utf-8"))
    require((summary["overall"]["n"], summary["overall"]["correct"], len(summary["answer_changes"]))
            == (12, 8, 3), "Synthetic result must be 12 responses, 8 correct, and 3 revisions")
    conditions = [[row["condition"], row["n"], row["correct"]] for row in summary["by_condition"]]
    require(conditions == EXPECTED_CONDITIONS, "Synthetic condition counts differ")
    with sqlite3.connect(f"{(run / 'analysis.sqlite').resolve().as_uri()}?mode=ro", uri=True) as conn:
        for table, count in EXPECTED_COUNTS.items():
            actual = conn.execute(f"SELECT COUNT(*) FROM {quoted_identifier(table)}").fetchone()[0]
            require(actual == count, f"Unexpected SQLite row count: {table}")
        counts = [list(row) for row in conn.execute(
            "SELECT condition, COUNT(*), SUM(doctor_is_correct) FROM scored_responses "
            "GROUP BY condition ORDER BY condition")]
        require(counts == EXPECTED_CONDITIONS, "Independent SQL condition counts differ")


def verify_run(run, reference, strict):
    """Validate existing output; exposed separately so corruption tests use real files."""
    actual = hashes(run)
    require(actual.keys() == strict.keys(), "Output file set differs from the reviewed 22 files")
    for name in sorted(strict.keys() - PLATFORM_FILES):
        require(actual[name] == strict[name], f"Text/input reference hash mismatch: {name}")
    require(database_content(run / "analysis.sqlite") == reference["database"],
            "SQLite schema, values, storage types, or logical metadata differ from reviewed reference")
    verify_manifest(run, reference, actual)
    verify_known_results(run)
    return actual


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output-dir", type=Path, required=True, help="New directory; never overwritten")
    args = parser.parse_args()
    import numpy
    require(numpy.__version__ == "2.2.6", "Install requirements.lock: NumPy 2.2.6 is required")
    reference, strict = load_reference()
    source = (FIXTURE / "snapshot").resolve()
    output = args.output_dir.resolve()
    require(source != output and source not in output.parents and output not in source.parents,
            "Output and fixture directories must be separate")
    before = hashes(source)
    expected_inputs = {name.removeprefix("snapshot/"): digest for name, digest in strict.items()
                       if name.startswith("snapshot/")}
    require(before == expected_inputs, "Bundled synthetic inputs differ from the reviewed reference")
    output.mkdir(parents=True, exist_ok=False)
    print(f"Execution time: {datetime.now(timezone.utc).isoformat()}", flush=True)
    print(f"Python={platform.python_version()} NumPy={numpy.__version__} SQLite={sqlite3.sqlite_version} "
          f"OS={platform.system()} arch={platform.machine()}", flush=True)
    print("Fixed synthetic inputs; seed=20261019; bootstrap_reps=1000; "
          "explicit_provenance_time=2026-01-01T00:00:00+00:00", flush=True)
    runs = []
    for number in (1, 2):
        run = output / f"run-{number}"
        shutil.copytree(source, run / "snapshot")
        proc = subprocess.run([sys.executable, str(SCRIPTS / "analyze_real_doctor_collection.py"),
                               "--snapshot-dir", str(run), "--seed", "20261019",
                               "--bootstrap-reps", "1000", "--generated-at", "2026-01-01T00:00:00+00:00"],
                              capture_output=True, text=True)
        if proc.returncode:
            print(proc.stdout, proc.stderr)
            raise RuntimeError(f"Analysis run {number} failed: {proc.returncode}")
        runs.append(verify_run(run, reference, strict))
        print(f"PASS run-{number}: 20 committed file hashes; complete SQLite content/schema; "
              "manifest; independent synthetic/SQL counts (12 responses, 8 correct, 3 revisions).", flush=True)
    require(hashes(source) == before, "Source inputs changed during verification")
    require(runs[0] == runs[1], "Two runs differ in file set or SHA-256")
    print("PASS CROSS-PLATFORM: all 22 files match byte-for-byte between two runs in this environment. "
          "20 files match the committed macOS hashes; SQLite and manifest pass the reviewed semantic checks. "
          "This does not certify 22-file byte equality with the macOS reference. "
          "No reference was regenerated.", flush=True)


if __name__ == "__main__":
    try:
        main()
    except (ValueError, RuntimeError, OSError, KeyError, TypeError, sqlite3.Error) as exc:
        print(f"FAIL: {exc}", file=sys.stderr)
        sys.exit(1)
